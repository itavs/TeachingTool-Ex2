class ReviewContractTests(SimpleTestCase):
    def test_zero_points_exact_quotes_language_and_timestamp_binding(self):
        segments=[{'start':1.0,'end':3.0,'text':'A class describes objects.'}]
        self.assertEqual(validate_review({'points':[]},segments,'en'),[])
        point={'quote':'class describes',
               'suggestion':'Check whether the example makes the relationship explicit.'}
        self.assertEqual(validate_review({'points':[point]},segments,'en')[0]['start'],1)
        for invalid in [{**point,'quote':'not in source'},{**point,'quote':''}]:
            with self.assertRaises(ValueError):validate_review({'points':[invalid]},segments,'en')
        with self.assertRaises(ValueError):validate_review({'points':[point]*3},segments,'en')
        self.assertIn('Zero points is valid',review_prompt(segments,'en'))
        joined=[{'start':0,'end':1,'text':' A class'}, {'start':1,'end':2,'text':' describes objects.'}]
        spanning={**point,'quote':'class describes'}
        checked=validate_review({'points':[spanning]},joined,'en')[0]
        self.assertEqual((checked['start'],checked['end']),(0,2))


@override_settings(PASSWORD_HASHERS=['django.contrib.auth.hashers.MD5PasswordHasher'])
class OptionalReviewTests(ParticipationFixture,TransactionTestCase):
    setUp=summary_fixtures.SummaryTests.setUp
    tearDown=summary_fixtures.SummaryTests.tearDown
    url=summary_fixtures.SummaryTests.url

    def finish(self,engine):
        job=summary_fixtures.SummaryTests.new_job(self)
        VideoJob.objects.filter(pk=job.pk).update(lecturer_review_requested=True)
        job=claim_job()
        process_job(job,transcriber=FakeTranscriber(),summarizer=summary_fixtures.FakeSummarizer(),lecturer_reviewer=engine)
        job.refresh_from_db();return job

    def test_zero_points_complete_and_failure_keeps_summary_transcript(self):
        engine=Mock();engine.review.return_value={'points':[],'metadata':{'test_only':True}}
        job=self.finish(engine)
        self.assertEqual((job.status,job.lecturer_review_status),('summarized','completed'))
        self.assertTrue(summary_available(job))
        engine.review.side_effect=ValueError('private error')
        job=self.finish(engine)
        self.assertEqual((job.status,job.lecturer_review_status),('summarized','failed'))
        self.assertTrue(summary_available(job));self.assertTrue(transcript_available(job))
        self.client.force_login(self.teacher)
        page=self.client.get(self.url('video-detail',job))
        self.assertContains(page,'Points for lecturer review could not be completed')
        self.assertNotContains(page,'private error')

    def test_invalid_quote_rejected_expiry_and_access(self):
        engine=Mock();engine.review.return_value={'points':[{'quote':'invented',
            'suggestion':'Check this.'}],'metadata':{}}
        job=self.finish(engine)
        self.assertEqual(job.lecturer_review_status,'failed')
        self.assertEqual(job.lecturer_review_points,[])
        self.client.force_login(self.student)
        self.assertEqual(self.client.get(self.url('video-detail',job)).status_code,403)
        Membership.objects.create(user=self.outsider,course=self.course,role='lecturer')
        self.client.force_login(self.outsider)
        self.assertEqual(self.client.get(self.url('video-detail',job)).status_code,404)
        VideoJob.objects.filter(pk=job.pk).update(lecturer_review_points=[{'quote':'expired'}],
            transcript_expires_at=timezone.now()-timedelta(seconds=1))
        cleanup_video_files();job.refresh_from_db()
        self.assertEqual(job.lecturer_review_points,[])

    def test_valid_point_renders_quote_time_and_hides_content_in_state(self):
        engine=Mock();engine.review.return_value={'points':[{'quote':'משתנה static',
            'suggestion':'בדוק אם המושג מוסבר בדוגמה.'}],'metadata':{'test_only':True}}
        job=self.finish(engine)
        self.assertEqual(job.lecturer_review_status,'completed')
        self.client.force_login(self.teacher)
        page=self.client.get(self.url('video-detail',job))
        self.assertContains(page,'Points for lecturer review')
        self.assertContains(page,'משתנה static')
        self.assertContains(page,'Transcript segment: 0.00–0.50 seconds')
        state=self.client.get(self.url('video-state',job)).json()
        self.assertNotIn('lecturer_review_points',state)

    def test_review_interruption_preserves_completed_summary(self):
        engine=Mock();engine.review.return_value={'points':[]}
        job=self.finish(engine)
        VideoJob.objects.filter(pk=job.pk).update(status='reviewing',lecturer_review_status='running')
        fail_job(job.pk,'interrupted');job.refresh_from_db()
        self.assertTrue(summary_available(job));self.assertEqual(job.lecturer_review_error,'interrupted')
