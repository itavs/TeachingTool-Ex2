class Command(BaseCommand):
    help = 'Create two clearly labeled local demo poll drafts, never AI-generated. Does not publish or overwrite existing polls.'

    def add_arguments(self, parser):
        parser.add_argument('--meeting-id', type=int, help='Target meeting ID; defaults to the first DEMO-CS101 meeting.')
        parser.add_argument('--language', choices=['he','en'], default='he')
        parser.add_argument('--new-set', action='store_true', help='Create another pair; otherwise preserve the existing named demo pair.')

    @transaction.atomic
    def handle(self, *args, **options):
        meetings = Meeting.objects.select_for_update()
        meeting = meetings.filter(pk=options['meeting_id']).first() if options['meeting_id'] else meetings.filter(course__code='DEMO-CS101').first()
        if meeting is None:
            raise CommandError('Target meeting not found. Prepare demo courses/meetings or supply --meeting-id.')
        suffix = '-' + uuid.uuid4().hex[:12] if options['new_set'] else ''
        material, entries = samples(options['language'])
        for kind, question, choices, correct, explanation in entries:
            poll, created = Poll.objects.get_or_create(meeting=meeting, demo_key=f'unit-c-{kind}-{options["language"]}{suffix}',
                defaults={'kind':kind,'language':options['language'],'material':material,'question':question,
                    'options':choices,'correct_index':correct,'explanation':explanation,
                    'origin':'demo','created_at':timezone.now()})
            self.stdout.write(f'{"Created" if created else "Preserved"} demo poll {poll.pk}: {kind}; meeting {meeting.pk}; {poll.status}. Not generated by AI.')
